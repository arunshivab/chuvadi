#!/usr/bin/env python3
"""Generates src/Chuvadi.Layout/Text/Generated/UnicodeTextData.cs: per-code-point properties for
UAX #14 line breaking and UAX #29 grapheme clusters, from UCD 16.0.0.

Usage: python3 gen_textprops.py <ucd-dir> <output.cs>
Needs: LineBreak.txt, GraphemeBreakProperty.txt, DerivedCoreProperties.txt (InCB),
       EastAsianWidth.txt, emoji-data.txt, DerivedGeneralCategory.txt (extracted/).

Packed value bits:
   0-5  Line_Break (raw, before LB1 resolution), index into LB below
   6-9  Grapheme_Cluster_Break, index into GCB below
  10-11 Indic_Conjunct_Break: 0 None, 1 Linker, 2 Consonant, 3 Extend
  12    East_Asian_Width in {F, W, H}
  13    Extended_Pictographic
  14    General_Category = Pi
  15    General_Category = Pf
  16    General_Category = Cn
  17    General_Category in {Mn, Mc}
"""
import sys, os
LB = ["BK","CR","LF","CM","NL","SG","WJ","ZW","GL","SP","ZWJ","B2","BA","BB","HY","CB","CL","CP","EX","IN",
      "NS","OP","QU","IS","NU","PO","PR","SY","AI","AK","AL","AP","AS","CJ","EB","EM","H2","H3","HL","ID",
      "JL","JV","JT","RI","SA","VF","VI","XX"]
GCB = ["Other","CR","LF","Control","Extend","ZWJ","Regional_Indicator","Prepend","SpacingMark","L","V","T","LV","LVT"]
INCB = {"None":0,"Linker":1,"Consonant":2,"Extend":3}
N = 0x110000
ucd, out = sys.argv[1], sys.argv[2]

def parse(fname, handler, field_index=1, filt=None):
    path = os.path.join(ucd, fname)
    missing = []
    entries = []
    for line in open(path, encoding='utf-8'):
        if line.startswith('# @missing:'):
            body = line[len('# @missing:'):].strip()
            parts = [p.strip() for p in body.split(';')]
            missing.append(parts)
            continue
        line = line.split('#')[0].strip()
        if not line: continue
        parts = [p.strip() for p in line.split(';')]
        entries.append(parts)
    for parts in missing + entries:
        if filt and not filt(parts): continue
        a, _, b = parts[0].partition('..')
        a = int(a, 16); b = int(b, 16) if b else a
        handler(a, b, parts)

lb = [LB.index("XX")] * N
def h_lb(a, b, p):
    v = LB.index(p[1])
    for c in range(a, b+1): lb[c] = v
parse("LineBreak.txt", h_lb)

gcb = [0] * N
def h_gcb(a, b, p):
    v = GCB.index(p[1])
    for c in range(a, b+1): gcb[c] = v
parse("GraphemeBreakProperty.txt", h_gcb)

incb = [0] * N
def h_incb(a, b, p):
    v = INCB[p[2]]
    for c in range(a, b+1): incb[c] = v
parse("DerivedCoreProperties.txt", h_incb, filt=lambda p: len(p) >= 3 and p[1] == "InCB")

ea = [0] * N
def h_ea(a, b, p):
    v = 1 if p[1] in ("F","W","H") else 0
    for c in range(a, b+1): ea[c] = v
parse("EastAsianWidth.txt", h_ea)

ep = [0] * N
def h_ep(a, b, p):
    for c in range(a, b+1): ep[c] = 1
parse("emoji-data.txt", h_ep, filt=lambda p: p[1] == "Extended_Pictographic")

gc = ["Cn"] * N
def h_gc(a, b, p):
    for c in range(a, b+1): gc[c] = p[1]
parse("DerivedGeneralCategory.txt", h_gc)

vals = []
for c in range(N):
    g = gc[c]
    v = lb[c] | (gcb[c] << 6) | (incb[c] << 10) | (ea[c] << 12) | (ep[c] << 13)
    v |= (1 << 14) if g == "Pi" else 0
    v |= (1 << 15) if g == "Pf" else 0
    v |= (1 << 16) if g == "Cn" else 0
    v |= (1 << 17) if g in ("Mn","Mc") else 0
    vals.append(v)
starts, packed = [], []
prev = None
for c in range(N):
    if vals[c] != prev:
        starts.append(c); packed.append(vals[c]); prev = vals[c]
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write("// <auto-generated>\n// Generated by docs/Chuvadi.Layout/tools/gen_textprops.py from UCD 16.0.0.\n// Do not edit by hand.\n// </auto-generated>\n\n")
    f.write("namespace Chuvadi.Layout.Text\n{\n    internal static class UnicodeTextData\n    {\n")
    f.write("        public static readonly int[] RangeStarts =\n        {\n")
    for i in range(0, len(starts), 12):
        f.write("            " + ", ".join(f"0x{s:X}" for s in starts[i:i+12]) + ",\n")
    f.write("        };\n\n        public static readonly int[] RangeValues =\n        {\n")
    for i in range(0, len(packed), 12):
        f.write("            " + ", ".join(f"0x{v:X}" for v in packed[i:i+12]) + ",\n")
    f.write("        };\n    }\n}\n")
print(len(starts), "ranges")
