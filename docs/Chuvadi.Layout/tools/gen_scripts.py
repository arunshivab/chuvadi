#!/usr/bin/env python3
"""Generates src/Chuvadi.Layout/Text/Generated/UnicodeScriptData.cs from UCD Scripts.txt.

Usage: python3 gen_scripts.py <path-to-Scripts.txt> <output.cs>
Unicode Character Database 16.0.0, https://www.unicode.org/Public/16.0.0/ucd/Scripts.txt
"""
import sys, re
ENUM = ["Unknown","Common","Inherited","Latin","Greek","Cyrillic","Armenian","Hebrew","Arabic","Syriac",
        "Thaana","Devanagari","Bengali","Gurmukhi","Gujarati","Oriya","Tamil","Telugu","Kannada","Malayalam",
        "Sinhala","Thai","Lao","Tibetan","Myanmar","Georgian","Hangul","Ethiopic","Khmer","Mongolian",
        "Hiragana","Katakana","Bopomofo","Han","Other"]
idx = {n:i for i,n in enumerate(ENUM)}
src, out = sys.argv[1], sys.argv[2]
cps = {}
version = None
for line in open(src, encoding='utf-8'):
    if version is None and line.startswith('# Scripts-'):
        version = line[2:].strip()
    line = line.split('#')[0].strip()
    if not line: continue
    rng, name = [x.strip() for x in line.split(';')]
    a, _, b = rng.partition('..')
    a = int(a,16); b = int(b,16) if b else a
    v = idx.get(name, idx['Other'])
    for c in range(a, b+1): cps[c] = v
starts, vals = [], []
prev = None
for c in range(0, 0x110000):
    v = cps.get(c, 0)
    if v != prev:
        starts.append(c); vals.append(v); prev = v
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write("// <auto-generated>\n")
    f.write(f"// Generated by docs/Chuvadi.Layout/tools/gen_scripts.py from UCD {version}.\n")
    f.write("// Do not edit by hand.\n// </auto-generated>\n\n")
    f.write("namespace Chuvadi.Layout.Text\n{\n    internal static class UnicodeScriptData\n    {\n")
    f.write(f"        public const string UnicodeVersion = \"16.0.0\";\n\n")
    f.write("        public static readonly int[] RangeStarts =\n        {\n")
    for i in range(0, len(starts), 12):
        f.write("            " + ", ".join(f"0x{s:X}" for s in starts[i:i+12]) + ",\n")
    f.write("        };\n\n        public static readonly byte[] RangeScripts =\n        {\n")
    for i in range(0, len(vals), 24):
        f.write("            " + ", ".join(str(v) for v in vals[i:i+24]) + ",\n")
    f.write("        };\n    }\n}\n")
print(len(starts), "ranges")
