using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;

namespace Chuvadi.Sheets.GuideSnippets;

/// <summary>
/// Keeps the C# examples in docs/Chuvadi.Sheets/GUIDE.md honest.
///
///   --extract   reads GUIDE.md and writes Snippets.g.cs: one method per ```csharp block, in order, with #line
///               directives so a compile error points at the line in GUIDE.md. A block whose first code line
///               declares a type (public/internal/record/class/enum, or an attribute) is placed at file scope
///               instead, so examples can declare the types they use.
///   (no args)   runs every example in order, in a fresh temporary folder, and reports each failure with its
///               line in GUIDE.md. Examples that only declare a local function compile but do not run.
/// </summary>
internal static class Program
{
    private static int Main(string[] args)
    {
        string toolDir = FindToolDir();
        string guide = Path.GetFullPath(Path.Combine(toolDir, "..", "..", "GUIDE.md"));
        if (args.Length > 0 && args[0] == "--extract") return Extract(guide, Path.Combine(toolDir, "Snippets.g.cs"));
        return RunAll(guide);
    }

    // ---- extract ------------------------------------------------------------------------------------------

    private static int Extract(string guide, string output)
    {
        var lines = File.ReadAllLines(guide, new UTF8Encoding(false));
        var bodies = new List<(int Line, string Heading, List<string> Code)>();
        var topLevel = new List<(int Line, List<string> Code)>();
        string heading = "";
        for (int i = 0; i < lines.Length; i++)
        {
            if (lines[i].StartsWith("#", StringComparison.Ordinal) && !lines[i].StartsWith("#!", StringComparison.Ordinal))
                heading = lines[i].TrimStart('#', ' ');
            if (lines[i].Trim() != "```csharp") continue;
            int start = i + 1;
            var code = new List<string>();
            for (i = start; i < lines.Length && lines[i].Trim() != "```"; i++) code.Add(lines[i]);
            string first = code.Select(l => l.Trim()).FirstOrDefault(l => l.Length > 0 && !l.StartsWith("//", StringComparison.Ordinal)) ?? "";
            bool isType = first.StartsWith("public ", StringComparison.Ordinal) || first.StartsWith("internal ", StringComparison.Ordinal)
                || first.StartsWith("record ", StringComparison.Ordinal) || first.StartsWith("class ", StringComparison.Ordinal)
                || first.StartsWith("enum ", StringComparison.Ordinal) || first.StartsWith("[", StringComparison.Ordinal);
            if (isType) topLevel.Add((start + 1, code)); else bodies.Add((start + 1, heading, code));
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> by Chuvadi.Sheets.GuideSnippets --extract from GUIDE.md. Do not edit. </auto-generated>");
        sb.AppendLine("#nullable enable");
        foreach (var u in new[] { "System", "System.Collections.Generic", "System.Data", "System.Globalization", "System.IO", "System.Linq",
                     "System.Text", "System.Threading", "System.Threading.Tasks", "Chuvadi.Sheets.Model" })
            sb.AppendLine($"using {u};");
        sb.AppendLine();
        sb.AppendLine("namespace Chuvadi.Sheets.GuideSnippets.Generated");
        sb.AppendLine("{");
        foreach (var (line, code) in topLevel)
        {
            sb.AppendLine($"#line {line} \"GUIDE.md\"");
            foreach (var l in code) sb.AppendLine(l);
            sb.AppendLine("#line default");
        }
        sb.AppendLine("    internal static class Snippets");
        sb.AppendLine("    {");
        sb.AppendLine("        public static readonly (int Line, string Heading, Func<Task> Run)[] All =");
        sb.AppendLine("        {");
        foreach (var (line, h, _) in bodies)
            sb.AppendLine($"            ({line}, \"{h.Replace("\\", "\\\\").Replace("\"", "\\\"")}\", S{line}),");
        sb.AppendLine("        };");
        foreach (var (line, _, code) in bodies)
        {
            bool isAsync = code.Any(l => l.Contains("await ", StringComparison.Ordinal));
            sb.AppendLine(isAsync ? $"        private static async Task S{line}()" : $"        private static Task S{line}()");
            sb.AppendLine("        {");
            sb.AppendLine($"#line {line} \"GUIDE.md\"");
            foreach (var l in code) sb.AppendLine(l);
            sb.AppendLine("#line default");
            if (!isAsync) sb.AppendLine("            return Task.CompletedTask;");
            sb.AppendLine("        }");
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");
        File.WriteAllText(output, sb.ToString(), new UTF8Encoding(false));
        Console.WriteLine($"{guide}: {bodies.Count} examples to run, {topLevel.Count} type declarations -> {output}");
        return 0;
    }

    // ---- run ----------------------------------------------------------------------------------------------

    private static int RunAll(string guide)
    {
        var type = Type.GetType("Chuvadi.Sheets.GuideSnippets.Generated.Snippets");
        var field = type?.GetField("All", BindingFlags.Public | BindingFlags.Static);
        if (field?.GetValue(null) is not ValueTuple<int, string, Func<System.Threading.Tasks.Task>>[] all)
        {
            Console.Error.WriteLine("No Snippets.g.cs: run with --extract first, then run again.");
            return 2;
        }

        string work = Path.Combine(Path.GetTempPath(), "chuvadi-guide-snippets-" + Guid.NewGuid().ToString("N")[..8]);
        Directory.CreateDirectory(work);
        string original = Directory.GetCurrentDirectory();
        Directory.SetCurrentDirectory(work);
        int failed = 0;
        var console = Console.Out;
        try
        {
            foreach (var (line, heading, run) in all)
            {
                var captured = new StringWriter();
                Console.SetOut(captured);
                var sw = Stopwatch.StartNew();
                Exception? error = null;
                try { run().GetAwaiter().GetResult(); }
                catch (Exception ex) { error = ex; }
                Console.SetOut(console);
                if (error is null)
                {
                    Console.WriteLine($"PASS  GUIDE.md:{line}  {heading}  ({sw.ElapsedMilliseconds} ms)");
                    foreach (var outLine in captured.ToString().Split('\n', StringSplitOptions.RemoveEmptyEntries))
                        Console.WriteLine("        | " + outLine.TrimEnd('\r'));
                }
                else
                {
                    failed++;
                    Console.WriteLine($"FAIL  GUIDE.md:{line}  {heading}");
                    Console.WriteLine($"        {error.GetType().Name}: {error.Message}");
                    if (error.InnerException is { } inner) Console.WriteLine($"        inner {inner.GetType().Name}: {inner.Message}");
                }
            }
        }
        finally
        {
            Console.SetOut(console);
            Directory.SetCurrentDirectory(original);
            try { Directory.Delete(work, recursive: true); } catch (IOException) { }
        }
        Console.WriteLine();
        Console.WriteLine($"{all.Length} examples: {all.Length - failed} passed, {failed} failed.");
        return failed == 0 ? 0 : 1;
    }

    private static string FindToolDir()
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            string candidate = Path.Combine(dir.FullName, "docs", "Chuvadi.Sheets", "tools", "GuideSnippets");
            if (File.Exists(Path.Combine(candidate, "Chuvadi.Sheets.GuideSnippets.csproj"))) return candidate;
        }
        for (var dir = new DirectoryInfo(Directory.GetCurrentDirectory()); dir is not null; dir = dir.Parent)
        {
            string candidate = Path.Combine(dir.FullName, "docs", "Chuvadi.Sheets", "tools", "GuideSnippets");
            if (File.Exists(Path.Combine(candidate, "Chuvadi.Sheets.GuideSnippets.csproj"))) return candidate;
        }
        throw new DirectoryNotFoundException("docs/Chuvadi.Sheets/tools/GuideSnippets not found above " + AppContext.BaseDirectory);
    }
}
