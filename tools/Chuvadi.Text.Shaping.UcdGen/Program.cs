// Unicode table generator for Chuvadi.Text.Shaping. Reads the Unicode Character
// Database text files (UAX #44 formats) and writes one C# file of compact
// lookup tables. The output depends only on the input files, so running it
// twice on the same files gives the same bytes.

using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;

namespace Chuvadi.Text.Shaping.UcdGen;

internal static class Program
{
    private const int MaxCodePoint = 0x10FFFF;
    private const int TopShift = 12;
    private const int BlockShift = 6;
    private const int BlockSize = 1 << BlockShift;
    private const int MidSize = 1 << (TopShift - BlockShift);

    // TRACE R-TS-0001
    private static readonly string[] GeneralCategories =
    {
        "Cn", "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe",
        "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co",
    };

    private static readonly string[] InputFiles =
    {
        "UnicodeData.txt", "IndicSyllabicCategory.txt", "IndicPositionalCategory.txt", "DerivedCoreProperties.txt",
        "Scripts.txt", "PropertyValueAliases.txt", "CompositionExclusions.txt",
    };

    private static int Main(string[] args)
    {
        if (args.Length != 2)
        {
            Console.Error.WriteLine("usage: UcdGen <ucd directory> <output .g.cs file>");
            return 2;
        }

        string dir = args[0];
        string output = args[1];
        string version = ReadVersion(Path.Combine(dir, "Scripts.txt"));

        byte[] gc = new byte[MaxCodePoint + 1];
        byte[] ccc = new byte[MaxCodePoint + 1];
        Dictionary<int, int[]> decomposition = new Dictionary<int, int[]>();
        ReadUnicodeData(Path.Combine(dir, "UnicodeData.txt"), gc, ccc, decomposition);

        string[] iscNames = ReadEnumeratedNames(Path.Combine(dir, "IndicSyllabicCategory.txt"), "Other");
        byte[] isc = ReadEnumeratedProperty(Path.Combine(dir, "IndicSyllabicCategory.txt"), iscNames);
        string[] ipcNames = ReadEnumeratedNames(Path.Combine(dir, "IndicPositionalCategory.txt"), "NA");
        byte[] ipc = ReadEnumeratedProperty(Path.Combine(dir, "IndicPositionalCategory.txt"), ipcNames);
        bool[] ignorable = ReadBinaryProperty(Path.Combine(dir, "DerivedCoreProperties.txt"), "Default_Ignorable_Code_Point");

        (string[] scriptCodes, byte[] script) = ReadScripts(Path.Combine(dir, "Scripts.txt"), Path.Combine(dir, "PropertyValueAliases.txt"));

        HashSet<int> exclusions = ReadCodePointList(Path.Combine(dir, "CompositionExclusions.txt"));

        // Packed property record: gc (5 bits) | ccc (8) | isc (6) | ipc (5) | default ignorable (1).
        uint[] packed = new uint[MaxCodePoint + 1];
        for (int cp = 0; cp <= MaxCodePoint; cp++)
        {
            packed[cp] = gc[cp] | ((uint)ccc[cp] << 5) | ((uint)isc[cp] << 13) | ((uint)ipc[cp] << 19) | (ignorable[cp] ? 1u << 24 : 0u);
        }

        (byte[] propIds, uint[] propRecords) = Records(packed);
        (ushort[] propStage1, ushort[] propStage2, byte[] propStage3) = ThreeStage(propIds);
        (ushort[] scriptStage1, ushort[] scriptStage2, byte[] scriptStage3) = ThreeStage(script);

        // TRACE R-TS-0002
        List<(int Cp, int A, int B)> decomp = decomposition.OrderBy(kv => kv.Key).Select(kv => (kv.Key, kv.Value[0], kv.Value.Length > 1 ? kv.Value[1] : -1)).ToList();
        List<(long Key, int Composite)> compositions = new List<(long, int)>();
        foreach ((int cp, int a, int b) in decomp)
        {
            bool fullExclusion = exclusions.Contains(cp) || b < 0 || ccc[cp] != 0 || ccc[a] != 0;
            if (!fullExclusion)
            {
                compositions.Add((((long)a << 21) | (uint)b, cp));
            }
        }

        compositions.Sort((x, y) => x.Key.CompareTo(y.Key));

        StringBuilder sb = new StringBuilder();
        sb.Append("// <auto-generated>\n");
        sb.Append("// Generated by tools/Chuvadi.Text.Shaping.UcdGen from the Unicode Character Database ").Append(version).Append(".\n");
        sb.Append("// Do not edit. Regenerate with the PowerShell commands in tools/Chuvadi.Text.Shaping.UcdGen/README.md.\n");
        sb.Append("// Input files (SHA-256):\n");
        foreach (string f in InputFiles)
        {
            sb.Append("//   ").Append(f).Append(' ').Append(Sha256(Path.Combine(dir, f))).Append('\n');
        }

        sb.Append("// Unicode data is Copyright Unicode, Inc. and used under the Unicode License v3; see Unicode/UnicodeLicense.txt.\n");
        sb.Append("// </auto-generated>\n\n");
        sb.Append("#pragma warning disable CS1591\n\n");
        sb.Append("using System;\n\n");
        sb.Append("namespace Chuvadi.Text.Shaping.Unicode;\n\n");

        AppendEnum(sb, "IndicSyllabicCategory", iscNames, "Indic_Syllabic_Category (IndicSyllabicCategory.txt).");
        AppendEnum(sb, "IndicPositionalCategory", ipcNames, "Indic_Positional_Category (IndicPositionalCategory.txt).");

        sb.Append("internal static partial class UnicodeData\n{\n");
        sb.Append("    internal const string Version = \"").Append(version).Append("\";\n\n");
        sb.Append("    internal const int TopShift = ").Append(TopShift).Append(";\n\n");
        sb.Append("    internal const int BlockShift = ").Append(BlockShift).Append(";\n\n");
        AppendArray(sb, "ushort", "PropertyStage1", propStage1);
        AppendArray(sb, "ushort", "PropertyStage2", propStage2);
        AppendArray(sb, "byte", "PropertyStage3", propStage3);
        AppendArray(sb, "uint", "PropertyRecords", propRecords);
        AppendArray(sb, "ushort", "ScriptStage1", scriptStage1);
        AppendArray(sb, "ushort", "ScriptStage2", scriptStage2);
        AppendArray(sb, "byte", "ScriptStage3", scriptStage3);
        sb.Append("    internal static readonly string[] ScriptCodes =\n    {\n");
        foreach (string code in scriptCodes)
        {
            sb.Append("        \"").Append(code).Append("\",\n");
        }

        sb.Append("    };\n\n");
        AppendArray(sb, "int", "DecompositionCodePoints", decomp.Select(d => d.Cp).ToArray());
        AppendArray(sb, "int", "DecompositionFirst", decomp.Select(d => d.A).ToArray());
        AppendArray(sb, "int", "DecompositionSecond", decomp.Select(d => d.B).ToArray());
        AppendArray(sb, "long", "CompositionKeys", compositions.Select(c => c.Key).ToArray());
        AppendArray(sb, "int", "CompositionValues", compositions.Select(c => c.Composite).ToArray());
        sb.Append("}\n");

        string text = sb.ToString();
        File.WriteAllText(output, text, new UTF8Encoding(false));
        int dataBytes = (2 * (propStage1.Length + propStage2.Length + scriptStage1.Length + scriptStage2.Length)) + propStage3.Length + scriptStage3.Length +
                        (4 * propRecords.Length) + (12 * decomp.Count) + (12 * compositions.Count);
        Console.WriteLine($"Unicode {version}: {propRecords.Length} property records, {propStage3.Length / BlockSize} property blocks, " +
                          $"{scriptStage3.Length / BlockSize} script blocks, {scriptCodes.Length} scripts, {decomp.Count} decompositions, " +
                          $"{compositions.Count} compositions, {dataBytes} bytes of table data.");
        return 0;
    }

    // TRACE R-TS-0001
    private static string ReadVersion(string scriptsPath)
    {
        // The first line of each UCD file names it with its version, for example "# Scripts-17.0.0.txt".
        string first = File.ReadLines(scriptsPath).First();
        int dash = first.LastIndexOf('-');
        int dot = first.LastIndexOf(".txt", StringComparison.Ordinal);
        if (dash < 0 || dot <= dash)
        {
            throw new InvalidDataException("Cannot read the UCD version from Scripts.txt.");
        }

        return first.Substring(dash + 1, dot - dash - 1);
    }

    // TRACE R-TS-0001
    private static void ReadUnicodeData(string path, byte[] gc, byte[] ccc, Dictionary<int, int[]> decomposition)
    {
        Dictionary<string, byte> gcIndex = new Dictionary<string, byte>(StringComparer.Ordinal);
        for (int i = 0; i < GeneralCategories.Length; i++)
        {
            gcIndex[GeneralCategories[i]] = (byte)i;
        }

        int rangeStart = -1;
        foreach (string line in File.ReadLines(path))
        {
            if (line.Length == 0)
            {
                continue;
            }

            string[] f = line.Split(';');
            int cp = int.Parse(f[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
            byte cat = gcIndex[f[2]];
            byte cc = byte.Parse(f[3], CultureInfo.InvariantCulture);
            if (f[1].EndsWith(", First>", StringComparison.Ordinal))
            {
                rangeStart = cp;
                continue;
            }

            int from = f[1].EndsWith(", Last>", StringComparison.Ordinal) ? rangeStart : cp;
            for (int c = from; c <= cp; c++)
            {
                gc[c] = cat;
                ccc[c] = cc;
            }

            rangeStart = -1;
            if (f[5].Length > 0 && f[5][0] != '<')
            {
                decomposition[cp] = f[5].Split(' ', StringSplitOptions.RemoveEmptyEntries)
                    .Select(h => int.Parse(h, NumberStyles.HexNumber, CultureInfo.InvariantCulture)).ToArray();
            }
        }
    }

    private static IEnumerable<(int From, int To, string Value)> ReadRanges(string path)
    {
        foreach (string raw in File.ReadLines(path))
        {
            int hash = raw.IndexOf('#');
            string line = (hash >= 0 ? raw.Substring(0, hash) : raw).Trim();
            if (line.Length == 0)
            {
                continue;
            }

            string[] f = line.Split(';');
            string range = f[0].Trim();
            string value = f.Length > 1 ? f[1].Trim() : string.Empty;
            int dots = range.IndexOf("..", StringComparison.Ordinal);
            int from = int.Parse(dots >= 0 ? range.Substring(0, dots) : range, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
            int to = dots >= 0 ? int.Parse(range.Substring(dots + 2), NumberStyles.HexNumber, CultureInfo.InvariantCulture) : from;
            yield return (from, to, value);
        }
    }

    private static string[] ReadEnumeratedNames(string path, string defaultName)
    {
        SortedSet<string> names = new SortedSet<string>(StringComparer.Ordinal);
        foreach ((_, _, string value) in ReadRanges(path))
        {
            if (value != defaultName)
            {
                _ = names.Add(value);
            }
        }

        return new[] { defaultName }.Concat(names).ToArray();
    }

    // TRACE R-TS-0003
    private static byte[] ReadEnumeratedProperty(string path, string[] names)
    {
        Dictionary<string, byte> index = names.Select((n, i) => (n, i)).ToDictionary(t => t.n, t => (byte)t.i, StringComparer.Ordinal);
        byte[] values = new byte[MaxCodePoint + 1];
        foreach ((int from, int to, string value) in ReadRanges(path))
        {
            for (int c = from; c <= to; c++)
            {
                values[c] = index[value];
            }
        }

        return values;
    }

    // TRACE R-TS-0004
    private static bool[] ReadBinaryProperty(string path, string property)
    {
        bool[] values = new bool[MaxCodePoint + 1];
        foreach ((int from, int to, string value) in ReadRanges(path))
        {
            if (value == property)
            {
                for (int c = from; c <= to; c++)
                {
                    values[c] = true;
                }
            }
        }

        return values;
    }

    // TRACE R-TS-0005
    private static (string[] Codes, byte[] Values) ReadScripts(string scriptsPath, string aliasesPath)
    {
        Dictionary<string, string> longToShort = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (string raw in File.ReadLines(aliasesPath))
        {
            string line = raw.Trim();
            if (!line.StartsWith("sc ", StringComparison.Ordinal) && !line.StartsWith("sc;", StringComparison.Ordinal))
            {
                continue;
            }

            string[] f = line.Split('#')[0].Split(';').Select(x => x.Trim()).ToArray();
            if (f.Length >= 3 && f[0] == "sc")
            {
                longToShort[f[2]] = f[1];
            }
        }

        List<string> codes = new List<string> { "Zzzz" };
        Dictionary<string, byte> index = new Dictionary<string, byte>(StringComparer.Ordinal) { ["Zzzz"] = 0 };
        byte[] values = new byte[MaxCodePoint + 1];
        foreach ((int from, int to, string name) in ReadRanges(scriptsPath))
        {
            string code = longToShort[name];
            if (!index.TryGetValue(code, out byte id))
            {
                id = checked((byte)codes.Count);
                codes.Add(code);
                index[code] = id;
            }

            for (int c = from; c <= to; c++)
            {
                values[c] = id;
            }
        }

        return (codes.ToArray(), values);
    }

    private static HashSet<int> ReadCodePointList(string path)
    {
        HashSet<int> set = new HashSet<int>();
        foreach ((int from, int to, string _) in ReadRanges(path))
        {
            for (int c = from; c <= to; c++)
            {
                _ = set.Add(c);
            }
        }

        return set;
    }

    private static (byte[] Ids, uint[] Records) Records(uint[] values)
    {
        Dictionary<uint, byte> recordIndex = new Dictionary<uint, byte>();
        List<uint> records = new List<uint>();
        byte[] ids = new byte[values.Length];
        for (int cp = 0; cp < values.Length; cp++)
        {
            if (!recordIndex.TryGetValue(values[cp], out byte id))
            {
                id = checked((byte)records.Count);
                records.Add(values[cp]);
                recordIndex[values[cp]] = id;
            }

            ids[cp] = id;
        }

        return (ids, records.ToArray());
    }

    // TRACE R-TS-0006
    // Three-stage lookup: value = Stage3[(Stage2[(Stage1[cp >> TopShift] * MidSize) + ((cp >> BlockShift) & (MidSize - 1))] * BlockSize) + (cp & (BlockSize - 1))].
    private static (ushort[] Stage1, ushort[] Stage2, byte[] Stage3) ThreeStage(byte[] values)
    {
        Dictionary<string, ushort> blockIndex = new Dictionary<string, ushort>(StringComparer.Ordinal);
        List<byte> stage3 = new List<byte>();
        ushort[] blocks = new ushort[values.Length >> BlockShift];
        for (int b = 0; b < blocks.Length; b++)
        {
            ArraySegment<byte> block = new ArraySegment<byte>(values, b << BlockShift, BlockSize);
            string key = Convert.ToHexString(block);
            if (!blockIndex.TryGetValue(key, out ushort bi))
            {
                bi = checked((ushort)(stage3.Count >> BlockShift));
                stage3.AddRange(block);
                blockIndex[key] = bi;
            }

            blocks[b] = bi;
        }

        Dictionary<string, ushort> midIndex = new Dictionary<string, ushort>(StringComparer.Ordinal);
        List<ushort> stage2 = new List<ushort>();
        ushort[] stage1 = new ushort[values.Length >> TopShift];
        for (int m = 0; m < stage1.Length; m++)
        {
            ArraySegment<ushort> mid = new ArraySegment<ushort>(blocks, m * MidSize, MidSize);
            string key = string.Join(",", mid);
            if (!midIndex.TryGetValue(key, out ushort mi))
            {
                mi = checked((ushort)(stage2.Count / MidSize));
                stage2.AddRange(mid);
                midIndex[key] = mi;
            }

            stage1[m] = mi;
        }

        return (stage1, stage2.ToArray(), stage3.ToArray());
    }

    private static void AppendEnum(StringBuilder sb, string name, string[] values, string doc)
    {
        sb.Append("/// <summary>").Append(doc).Append("</summary>\n");
        sb.Append("internal enum ").Append(name).Append(" : byte\n{\n");
        foreach (string v in values)
        {
            sb.Append("    ").Append(v.Replace("_", string.Empty, StringComparison.Ordinal)).Append(",\n");
        }

        sb.Append("}\n\n");
    }

    private static void AppendArray<T>(StringBuilder sb, string type, string name, T[] values)
        where T : IFormattable
    {
        sb.Append("    internal static ReadOnlySpan<").Append(type).Append("> ").Append(name).Append(" => new ").Append(type).Append("[]\n    {\n");
        for (int i = 0; i < values.Length; i += 16)
        {
            sb.Append("        ");
            for (int k = i; k < Math.Min(i + 16, values.Length); k++)
            {
                sb.Append(values[k].ToString(null, CultureInfo.InvariantCulture)).Append(", ");
            }

            sb.Length--;
            sb.Append('\n');
        }

        sb.Append("    };\n\n");
    }

    private static string Sha256(string path) => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path))).ToLowerInvariant();
}
